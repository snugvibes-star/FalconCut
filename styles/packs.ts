export function getPack(p: { stylePackId: string; customPacks: StylePack[] }, id?: string): StylePack {
  const want = id ?? p.stylePackId;
  return p.customPacks.find((x) => x.id === want) ?? BUILT_IN_PACKS.find((x) => x.id === want) ?? BUILT_IN_PACKS[0];
}