/**
 * In-memory clip clipboard for the timeline: copy, cut, paste and duplicate.
 *
 * Everything routes through the normal engine actions, so every paste is one
 * undo step and produces clips identical to hand-built ones (effects,
 * keyframes, fades, transforms, labels and transitions included). The buffer
 * lives in memory only — reloading the page clears it, like a scratch clipboard.
 */
import { useStore } from '../state/store';
import { getMedia, uid, type Action, type Clip, type Track } from '../../engine';

interface CopiedClip {
  clip: Clip;
  /** Offset from the earliest copied clip, so a multi-clip paste keeps its shape. */
  offset: number;
}

let buffer: CopiedClip[] = [];

/** Project switches must not carry clips whose mediaId belongs to another project. */
export function clearClipboard(): void { buffer = []; }

const clone = (c: Clip): Clip => JSON.parse(JSON.stringify(c)) as Clip;

function collect(ids: string[]): CopiedClip[] {
  const p = useStore.getState().project;
  const clips = p.clips.filter((c) => ids.includes(c.id));
  if (!clips.length) return [];
  const from = Math.min(...clips.map((c) => c.start));
  return clips.map((c) => ({ clip: clone(c), offset: c.start - from }));
}

/** Copy the current selection. Returns how many clips were copied. */
export function copySelection(): number {
  buffer = collect(useStore.getState().selection);
  return buffer.length;
}

/** Copy the selection, then remove it (one undo step). */
export function cutSelection(): number {
  const n = copySelection();
  if (!n) return 0;
  const s = useStore.getState();
  const applied = s.commit(s.selection.map((id) => ({ type: 'remove_clip' as const, clipId: id })), 'Cut clips');
  if (applied) s.select([]);
  return applied ? n : 0;
}

/** First track that can legally hold this clip, preferring the clip's own track. */
function trackFor(clip: Clip): Track | undefined {
  const p = useStore.getState().project;
  const want: Track['kind'] = clip.kind === 'media'
    ? (getMedia(p, clip.mediaId)?.type === 'audio' ? 'audio' : 'video')
    : 'text';
  const own = p.tracks.find((t) => t.id === clip.trackId);
  if (own && own.kind === want && !own.locked) return own;
  return p.tracks.find((t) => t.kind === want && !t.locked);
}

function paste(entries: CopiedClip[], at: number, label: string): number {
  if (!entries.length) return 0;
  const actions: Action[] = [];
  const p = useStore.getState().project;
  for (const { clip, offset } of entries) {
    // Copied media from another project has no matching asset here — pasting
    // it would create an invisible clip that still inflates the export.
    if (clip.kind === 'media' && clip.mediaId && !getMedia(p, clip.mediaId)) continue;
    const track = trackFor(clip);
    if (!track) continue;
    const next = clone(clip);
    // Absent ids are regenerated by the engine; media clips landing on
    // occupied space are clamped into the nearest free gap.
    delete (next as Partial<Clip>).id;
    next.trackId = track.id;
    next.start = Math.max(0, at + offset);
    next.keyframes = next.keyframes.map((k) => ({ ...k, id: undefined as unknown as string }));
    next.effects = next.effects.map((f) => ({ ...f, id: undefined as unknown as string }));
    actions.push({ type: 'add_clip', clip: next, nonce: uid('copy') });
  }
  if (!actions.length) return 0;
  useStore.getState().commit(actions, label);
  return actions.length;
}

/** Paste the clipboard at a timeline position (usually the playhead). */
export function pasteClipboard(at: number): number {
  return paste(buffer, at, 'Paste clips');
}

/** Duplicate the selection immediately after itself (same tracks, same look). */
export function duplicateSelection(): number {
  const entries = collect(useStore.getState().selection);
  if (!entries.length) return 0;
  const end = Math.max(...entries.map((e) => e.clip.start + e.clip.duration));
  return paste(entries, end, 'Duplicate clips');
}

/** How many clips are on the clipboard (for menu labels / disabled states). */
export function clipboardCount(): number {
  return buffer.length;
}
